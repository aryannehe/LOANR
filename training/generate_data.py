"""
Synthetic dataset generation (P7).

ALL DATA PRODUCED HERE IS SYNTHETIC. No public credit dataset was available under
data/raw/, so customer financial profiles are generated, not sourced. Every file
carries a header comment saying so and a SYNTHETIC column on every row, so the fact
survives being opened in a spreadsheet, re-saved, or partially copied
(CONTEXT.md section 11).

These people do not exist. This is not banking history and must never be presented
as any.

OFFLINE ONLY. Lives in training/, never imported by app/. Run:

    python -m training.generate_data
"""

import csv
import random
from pathlib import Path

from app.schemas.enums import (
    AssetType,
    EmploymentType,
    FeedbackEventType,
    FinancingStrategy,
    LoanPurpose,
    RiskAppetite,
)

DATA_DIR = Path("data")
SEED = 20260902
# 1200, not 400. The risk classifier learns a ~11% default rate, so 400 customers left
# roughly 46 positives and only ~10 in the held-out split — a test ROC-AUC computed on
# ten positives is dominated by draw noise, not by model quality. Tripling the
# population costs a minute of offline runtime and is the only honest way to shrink
# that variance in a synthetic dataset.
N_CUSTOMERS = 1200

# Share of customers deliberately generated with NO portfolio. The zero-portfolio
# path is first-class (CONTEXT.md non-negotiable 16), so it must be well represented
# in training, not a rare edge case the model never learns.
NO_PORTFOLIO_SHARE = 0.30

# Share of customers given seed interaction history. The rest are cold-start, which
# is likewise a first-class path.
WITH_HISTORY_SHARE = 0.40

SYNTHETIC_HEADER = (
    "# SYNTHETIC DATA — generated by training/generate_data.py. These customers, "
    "portfolios and interactions are fabricated. Not real banking data. Loan product "
    "lender names are real Indian lenders; their rates and limits are APPROXIMATE "
    "figures near published rate cards, not quotes, and imply no offer or approval."
)


